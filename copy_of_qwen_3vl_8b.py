def answer_to_text(answer):
    """
    Normalize different VQA answer formats into one target string.
    """
    if answer is None:
        return ""

    if isinstance(answer, str):
        return answer

    if isinstance(answer, (int, float)):
        return str(answer)

    if isinstance(answer, list):
        if len(answer) == 0:
            return ""

        # VQA may contain list[str]
        if all(isinstance(x, str) for x in answer):
            # use first answer for SFT
            return answer[0]

        # Sometimes list[dict]
        if isinstance(answer[0], dict):
            for key in ["answer", "text", "label"]:
                if key in answer[0]:
                    return str(answer[0][key])

        return str(answer[0])

    if isinstance(answer, dict):
        for key in ["answer", "text", "label"]:
            if key in answer:
                return str(answer[key])

    return str(answer)


class ManifestDataset(Dataset):

    def __init__(self, manifest_path):
        self.manifest_path = Path(manifest_path)

        self.records = []

        with self.manifest_path.open("r", encoding="utf-8") as f:
            for line in f:
                if not line.strip():
                    continue

                r = json.loads(line)

                question = r.get("question")
                answer = r.get("answer")
                image = r.get("image")

                if question is None or answer is None or image is None:
                    continue

                self.records.append(r)

        print(
            f"Loaded {len(self.records):,} usable examples "
            f"from {self.manifest_path}"
        )

    def __len__(self):
        return len(self.records)

    def __getitem__(self, idx):

        r = self.records[idx]

        image_path = r["image"]

        # In case image is a list
        if isinstance(image_path, list):
            image_path = image_path[0]

        image = Image.open(image_path).convert("RGB")

        question = str(r["question"]).strip()
        answer = answer_to_text(r["answer"]).strip()

        return {
            "id": r.get("id"),
            "dataset": r.get("dataset"),
            "image": image,
            "question": question,
            "answer": answer,
        }


class Qwen3VLCollator:
    """
    Builds multimodal Qwen3-VL SFT batches.

    Loss is applied only to assistant answer tokens.
    """

    def __init__(
        self,
        processor,
        max_length=2048,
    ):
        self.processor = processor
        self.max_length = max_length

    def __call__(self, examples):

        batch_inputs = []

        for x in examples:

            # Complete training conversation
            messages = [
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "image",
                            "image": x["image"],
                        },
                        {
                            "type": "text",
                            "text": x["question"],
                        },
                    ],
                },
                {
                    "role": "assistant",
                    "content": [
                        {
                            "type": "text",
                            "text": x["answer"],
                        }
                    ],
                },
            ]

            encoded = self.processor.apply_chat_template(
                messages,
                tokenize=True,
                add_generation_prompt=False,
                return_dict=True,
                return_tensors="pt",
            )

            # Remove singleton batch dimension.
            sample = {}

            for k, v in encoded.items():
                if torch.is_tensor(v):
                    sample[k] = v.squeeze(0)
                else:
                    sample[k] = v

            # ------------------------------------------------
            # Construct labels
            #
            # Better than training on prompt/image tokens.
            # Find answer boundary from prompt-only encoding.
            # ------------------------------------------------

            prompt_messages = [
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "image",
                            "image": x["image"],
                        },
                        {
                            "type": "text",
                            "text": x["question"],
                        },
                    ],
                }
            ]

            prompt_encoded = self.processor.apply_chat_template(
                prompt_messages,
                tokenize=True,
                add_generation_prompt=True,
                return_dict=True,
                return_tensors="pt",
            )

            prompt_len = prompt_encoded["input_ids"].shape[1]

            labels = sample["input_ids"].clone()

            # mask prompt tokens
            labels[:prompt_len] = -100

            sample["labels"] = labels

            batch_inputs.append(sample)

        return self._pad(batch_inputs)

    def _pad(self, examples):

        # Text tensors can use tokenizer padding.
        text_features = [
            {
                "input_ids": x["input_ids"],
                "attention_mask": x["attention_mask"],
                "labels": x["labels"],
            }
            for x in examples
        ]

        max_len = min(
            max(x["input_ids"].shape[0] for x in text_features),
            self.max_length,
        )

        pad_id = self.processor.tokenizer.pad_token_id

        input_ids = []
        attention_masks = []
        labels = []

        for x in text_features:

            ids = x["input_ids"][:max_len]
            mask = x["attention_mask"][:max_len]
            lab = x["labels"][:max_len]

            pad_len = max_len - len(ids)

            ids = torch.cat([
                ids,
                torch.full(
                    (pad_len,),
                    pad_id,
                    dtype=ids.dtype,
                )
            ])

            mask = torch.cat([
                mask,
                torch.zeros(
                    pad_len,
                    dtype=mask.dtype,
                )
            ])

            lab = torch.cat([
                lab,
                torch.full(
                    (pad_len,),
                    -100,
                    dtype=lab.dtype,
                )
            ])

            input_ids.append(ids)
            attention_masks.append(mask)
            labels.append(lab)

        batch = {
            "input_ids": torch.stack(input_ids),
            "attention_mask": torch.stack(attention_masks),
            "labels": torch.stack(labels),
        }

        # ----------------------------------------------------
        # Vision fields
        # Qwen processor generates these per sample.
        # Concatenate them across examples.
        # ----------------------------------------------------

        for key in [
            "pixel_values",
            "image_grid_thw",
            "mm_token_type_ids",
        ]:
            vals = [
                x[key]
                for x in examples
                if key in x and x[key] is not None
            ]

            if vals:
                try:
                    batch[key] = torch.cat(vals, dim=0)
                except Exception:
                    batch[key] = torch.stack(vals)

        return batch

