def normalize_answer(x):
    if x is None:
        return ""

    if isinstance(x, list):
        if len(x) == 0:
            return ""
        x = x[0]

    if isinstance(x, dict):
        x = (
            x.get("answer")
            or x.get("text")
            or x.get("label")
            or ""
        )

    return str(x).strip().lower()


